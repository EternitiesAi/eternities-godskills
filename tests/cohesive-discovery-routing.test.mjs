import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {searchCatalog, routeTask} from '../product/lib/product.mjs';

const evidence=new URL('../artifacts/qualification/cohesive-product-20261015/lane-c/',import.meta.url);
const matrix=JSON.parse(await readFile(new URL('matrix.frozen.json',evidence),'utf8'));
const catalog=JSON.parse(await readFile(new URL('catalog.frozen.json',evidence),'utf8'));

// Frozen development cases. This measures retrieval, not actual skill execution
// or unseen semantic accuracy. No shared manifest is generated by these tests.
for(const row of matrix.cases)test(`cohesive discovery ${row.id}: ${row.basis}`,()=>{
  const options={...matrix.options,need:row.need??matrix.options.need};
  const result=searchCatalog(catalog,row.query,options);
  const ids=result.results.map(item=>item.id);
  assert.equal(result.authority,'none');assert.equal(result.activation,'none');
  if(row.empty)assert.deepEqual(ids,[],JSON.stringify(ids));
  else assert.equal(result.selection.state,'review-required');
  if(row.owner)assert.ok(ids.includes(row.owner),JSON.stringify(ids));
  for(const id of row.exclude??[])assert.ok(!ids.includes(id),JSON.stringify(ids));
  if(row.nonempty)assert.ok(ids.length>0);
  const route=routeTask(catalog,row.query,{need:options.need,inputScope:'supplied-only',connectedPurpose:'none',discovery:'prohibited'},matrix.options);
  assert.deepEqual(route.search,result);
  assert.notEqual(route.atlas.connectedSource.state,'candidate');
});
